#!/usr/bin/env node
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "catalog/apps/immortal-launcher/upstream");
const meta = JSON.parse(readFileSync(join(dir, "meta.json"), "utf8"));
const repo = meta.repo;

const token = process.env.GITHUB_TOKEN;
const headers = {
	Accept: "application/vnd.github+json",
	...(token ? { Authorization: `Bearer ${token}` } : {}),
};

async function api(path) {
	const res = await fetch(`https://api.github.com/repos/${repo}/${path}`, {
		headers,
	});
	if (!res.ok) throw new Error(`GitHub API ${res.status} for ${path}`);
	return res.json();
}

async function raw(ref, path) {
	const res = await fetch(
		`https://raw.githubusercontent.com/${repo}/${ref}/${path}`,
	);
	if (!res.ok) throw new Error(`raw ${res.status} for ${path}`);
	return res.text();
}

// Optional fetches that return null on 404 (the program may not be published).
async function tryApi(path) {
	const res = await fetch(`https://api.github.com/repos/${repo}/${path}`, {
		headers,
	});
	return res.ok ? res.json() : null;
}

async function tryRaw(ref, path) {
	const res = await fetch(
		`https://raw.githubusercontent.com/${repo}/${ref}/${path}`,
	);
	return res.ok ? res.text() : null;
}

const PROGRAM_PATH = "provisioning/openportal.program.js";

const sha256 = (text) => createHash("sha256").update(text).digest("hex");

const argRef = process.argv[2];
const tag = argRef || (await api("releases/latest")).tag_name;
const commit = (await api(`commits/${tag}`)).sha;
const shFile = await api(`contents/provisioning/provision.sh?ref=${tag}`);
const envFile = await api(`contents/provisioning/config.env?ref=${tag}`);
const provisionSh = await raw(tag, "provisioning/provision.sh");
const configEnv = await raw(tag, "provisioning/config.env");
const programFile = await tryApi(`contents/${PROGRAM_PATH}?ref=${tag}`);
const programJs = await tryRaw(tag, PROGRAM_PATH);

writeFileSync(join(dir, "provision.sh"), provisionSh);
writeFileSync(join(dir, "config.env"), configEnv);

// Once Immortal publishes a program, vendor it as the offline fallback,
// replacing the built-in seed. Until then, keep the seed in place.
if (programFile && programJs) {
	writeFileSync(
		join(here, "..", "catalog/apps/immortal-launcher/program.js"),
		programJs,
	);
}

const newMeta = {
	...meta,
	vendoredCommit: commit,
	vendoredCommitShort: commit.slice(0, 7),
	latestReleaseTag: tag,
	provisionShBlob: shFile.sha,
	configEnvBlob: envFile.sha,
	provisionShSha256: sha256(provisionSh),
	configEnvSha256: sha256(configEnv),
	programBlob: programFile?.sha ?? null,
	programSha256: programJs ? sha256(programJs) : null,
	capturedAt: new Date().toISOString().slice(0, 10),
};
writeFileSync(
	join(dir, "meta.json"),
	`${JSON.stringify(newMeta, null, "\t")}\n`,
);

const snapshot = `// GENERATED by scripts/vendor-provision.mjs from ${repo} @ ${commit.slice(0, 7)}.
// Do not edit by hand. This is the offline fallback for the provisioning config;
// the live path fetches config.env from the latest release tag at runtime.
import meta from "./meta.json";

export const UPSTREAM_META = meta;

export const CONFIG_ENV_RAW = ${JSON.stringify(configEnv)};
`;
writeFileSync(join(dir, "snapshot.ts"), snapshot);

console.log(
	`Vendored ${repo}@${tag} (${commit.slice(0, 7)}). Review the diff; update catalog/apps/immortal-launcher/program.js if provision.sh changed.`,
);
